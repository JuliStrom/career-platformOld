function id(key) {
  return new mongoose.Types.ObjectId(createHash('sha256').update(`recommendation-demo-v1:${key}`).digest('hex').slice(0, 24));
}

async function main() {
  if (!process.env.MONGODB_URI) throw new Error('MONGODB_URI is missing');
  if (Object.values(Direction).some(direction => roles[direction]?.length !== 3)) throw new Error('Incomplete fixtures');
  await mongoose.connect(process.env.MONGODB_URI, { autoIndex: false, serverSelectionTimeoutMS: 15000 });
  console.log(`Database: ${mongoose.connection.name}`);
  let created = 0;
  for (const direction of Object.values(Direction)) {
    const companyName = `[Тест] Career Demo — ${direction}`;
    const companyId = id(`company:${direction}`);
    const company = new Company({
      _id: companyId, name: companyName, workFormat: 'Office', growthSpeed: 'Medium',
      teamSize: '11-50', languages: ['RU'], valuesTags: ['Обучение', 'Командная работа'],
      description: 'Тестовая компания для демонстрации подбора вакансий. Реальные заявки не принимаются.',
    });
    await company.validate();
    if (process.argv.includes('--apply')) {
      await Company.updateOne({ _id: companyId }, { $setOnInsert: company.toObject() }, { upsert: true });
    }
    for (const [index, [title, skills, duties]] of roles[direction].entries()) {
      const level = index === 0 ? 'Junior' : index === 1 ? 'Middle' : 'Senior';
      const responsibilities = duties.split('|');
      const job = new Job({
        _id: id(`job:${direction}:${index}`), title, company: companyName, companyId,
        direction, level, workFormat: index === 1 ? 'Hybrid' : 'Office',
        location: index === 2 ? 'Астана, Казахстан' : 'Алматы, Казахстан',
        description: `Демонстрационная вакансия: ${title}, уровень ${level}. ${responsibilities.join('. ')}. Работа в команде, вводное обучение и регулярная обратная связь. Тестовая запись для проверки подбора; реального найма нет.`,
        requirements: [...skills.split('|'), index === 0 ? 'Базовые знания и учебные проекты' : index === 1 ? 'Практический опыт от 2 лет' : 'Практический опыт от 4 лет'],
        responsibilities, salary: { min: 250000 + index * 150000, max: 400000 + index * 200000, currency: 'KZT' },
        isActive: true,
      });
      await job.validate();
      if (process.argv.includes('--apply')) {
        const result = await Job.updateOne({ _id: job._id }, { $setOnInsert: job.toObject() }, { upsert: true });
        created += result.upsertedCount;
      }
    }
    const active = await Job.countDocuments({ direction, isActive: true });
    console.log(`${direction}: active=${active}`);
    if (process.argv.includes('--apply') && active < 3) throw new Error(`Not enough jobs: ${direction}`);
  }
  console.log(process.argv.includes('--apply') ? `Created ${created} jobs. Existing records preserved.` : 'Validated 42 demo jobs; run with --apply to insert.');
}

main().catch(error => {
  console.error(`Seed failed (${error.name}): ${error.code || 'check connection or fixture validation'}`);
  process.exitCode = 1;
}).finally(() => mongoose.disconnect());
